"""Verify the current native Steam-ID join path; no game process access."""
import hashlib
import json
import struct
from pathlib import Path
from analyze_network_bindings import Analysis
from analyze_host_allocations import GAME_SHA256

root = Path(__file__).resolve().parents[1]
raw = Path('D:/Games/steamapps/common/MGS_TPP/mgsvtpp.exe').read_bytes()
assert hashlib.sha256(raw).hexdigest() == GAME_SHA256
a = Analysis(raw)
functions = [a.function(r) for r in (0x7ee380, 0x3144d0, 0x7d6470, 0x315140, 0x3152d0, 0x315be0)]
rows = {int(i['rva'], 16): (i['mnemonic'], i['operands'])
        for f in functions for i in f['instructions']}
checks = {
    0x7ee39e: ('mov', 'rbx, rdx'),
    0x7ee3a1: ('mov', 'rdi, rcx'),
    0x7ee3b4: ('cmp', 'dword ptr [rbx], 0'),
    0x7ee3c6: ('cmp', 'qword ptr [rax + 0xcc8], 0'),
    0x7ee4fd: ('mov', 'rax, qword ptr [rdi + 0x40]'),
    0x7ee501: ('mov', 'rcx, qword ptr [rax + 0xb8]'),
    0x7ee508: ('mov', 'qword ptr [rbp - 0x60], rcx'),
    0x7ee53f: ('lea', 'rcx, [rax + 0x20]'),
    0x7ee54a: ('call', 'qword ptr [rax + 0x40]'),
    0x7ee54d: ('mov', 'byte ptr [rdi + 0x48], 1'),
    0x7ee55a: ('mov', 'dword ptr [rdi + 0x10], 2'),
    0x7ee571: ('mov', 'al, 1'),
    0x31488b: ('mov', 'r8, qword ptr [r12 + 0x18]'),
    0x314895: ('call', 'qword ptr [rax + 0x20]'),
    0x31489f: ('mov', 'rdx, rax'),
    0x3148a2: ('call', '0x140016090'),
    0x3148a7: ('mov', 'dword ptr [rbx + 0x70], 4'),
    0x314573: ('mov', 'byte ptr [rbx + 0xc1], 0'),
    0x315140: ('mov', 'byte ptr [rcx + 0xe1], 1'),
    0x315147: ('ret', ''),
    0x3152eb: ('mov', 'eax, dword ptr [rbx + 0x90]'),
    0x3152f1: ('add', 'eax, -2'),
    0x3152f4: ('cmp', 'eax, 5'),
    0x315302: ('mov', 'ecx, dword ptr [rdx + rax*4 + 0x31535c]'),
    0x315350: ('jmp', '0x140315be0'),
    0x315c2e: ('cmp', 'ecx, 6'),
    0x315c37: ('cmp', 'byte ptr [rbx + 0xe1], r14b'),
    0x315c3e: ('je', '0x140315d0d'),
    0x315c60: ('mov', 'rax, qword ptr [rbx + 0x38]'),
    0x315c64: ('or', 'dword ptr [rax + 0x44], 0x10'),
    0x315c9b: ('mov', 'dword ptr [rbx + 0x90], 7'),
    0x7d6470: ('mov', 'rax, qword ptr [rcx + 0x30]'),
    0x7d6474: ('mov', 'rax, qword ptr [rax + 0x28]'),
}
for rva, expected in checks.items():
    assert rows.get(rva) == expected, (hex(rva), rows.get(rva))
assert struct.unpack('<Q', a.pe.rva_read(0x2127040 + 0x40, 8))[0] == a.pe.image_base + 0x3144d0
assert struct.unpack('<Q', a.pe.rva_read(0x2126f70 + 0x68, 8))[0] == a.pe.image_base + 0x315140
assert struct.unpack('<Q', a.pe.rva_read(0x2126f70 + 0x88, 8))[0] == a.pe.image_base + 0x3152d0
dispatch_bytes = a.pe.rva_read(0x31535c, 24)
assert struct.unpack('<6I', dispatch_bytes) == (0x31530e, 0x31530e, 0x31531b, 0x31533b, 0x315348, 0x315348)
for f in functions:
    if f['entry_rva'] == '0x3152d0':
        # This exception range ends in a six-entry data table, not instructions.
        assert f['decoded_bytes'] == 140
        assert int(f['entry_rva'], 16) + f['decoded_bytes'] == 0x31535c
        assert f['boundary']['end_rva_exclusive'] == '0x315374'
    else:
        assert f['complete_declared_range_decoded']
dispatch = {'entry_rva': '0x31535c', 'bytes': 24,
            'sha256': hashlib.sha256(dispatch_bytes).hexdigest(),
            'targets': [hex(r) for r in struct.unpack('<6I', dispatch_bytes)]}
report = {'executable_sha256': GAME_SHA256, 'instruction_checks': len(checks),
          'functions': functions, 'interface_table_rva': '0x2127040',
          'start_method_rva': '0x315140', 'start_slot_offset': '0x68',
          'start_flag_offset': '0xe1',
          'dispatch_table': dispatch,
          'start_requirement': 'Client preparation clears E1; native state 6 waits for E1 before publishing ready-member data and advancing to state 7.',
          'limitations': ['Static inspection only; no guest connection verified.',
                         'Native true means request started, not established.',
                         'Borrowed target and connection storage are never freed by the mod.']}
(root / 'docs/evidence/client-join-contract-2026-09-09.json').write_text(json.dumps(report, indent=2) + '\n')
lines = ['// Generated by tools/generate_client_join_contract.py.', '#pragma once',
         'constexpr SessionBodyContract client_join_bodies[] = {']
for f in functions:
    digest = ','.join(f'0x{b:02x}' for b in bytes.fromhex(f['decoded_bytes_sha256']))
    lines.append('    {' + f['entry_rva'] + ',' + str(f['decoded_bytes']) + ',{' + digest + '}},')
lines.append('    {0x31535c,24,{' + ','.join(f'0x{b:02x}' for b in bytes.fromhex(dispatch['sha256'])) + '}}, // dispatch data')
lines.append('};')
(root / 'native/client_join_contract.hpp').write_text('\n'.join(lines) + '\n')
print(f'{len(checks)} instruction checks, 3 interface slots and the state dispatch verified; {len(functions)} code contracts plus table contract emitted')
