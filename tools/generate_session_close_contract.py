"""Map existing session-close dispatch; static executable reads, no runtime calls."""
import hashlib
import json
import struct
from pathlib import Path
from analyze_network_bindings import Analysis
from analyze_host_allocations import GAME_SHA256

root=Path(__file__).resolve().parent.parent
path=Path('D:/Games/steamapps/common/MGS_TPP/mgsvtpp.exe')
raw=path.read_bytes()
assert hashlib.sha256(raw).hexdigest()==GAME_SHA256
a=Analysis(raw)
begin,end=0xA1A710,0xA1A781
instructions=a.instructions(begin,end-begin)
assert sum(i.size for i in instructions)==end-begin
rows={i.address-a.pe.image_base:(i.mnemonic,i.op_str) for i in instructions}
checks={
    0xA1A716:('call','0x140313780'),
    0xA1A721:('je','0x140a1a779'),
    0xA1A744:('mov','eax, 0xc382'),
    0xA1A749:('cmp','word ptr [rbx + 0x12], ax'),
    0xA1A759:('jne','0x140a1a76e'),
    0xA1A76E:('mov','rax, qword ptr [rdi + 0x20]'),
    0xA1A772:('lea','rcx, [rdi + 0x20]'),
    0xA1A776:('call','qword ptr [rax + 0x60]'),
    0xA1A780:('ret',''),
}
assert all(rows.get(rva)==expected for rva,expected in checks.items())
assert struct.unpack('<Q',a.pe.rva_read(0x2127040+0x60,8))[0]==a.pe.image_base+0x312B80
functions=[a.function(rva) for rva in [0x313780,0x312B80,0x314060]]
assert all(f['complete_declared_range_decoded'] for f in functions)
bodies=[(begin,a.pe.rva_read(begin,end-begin))]
bodies += [(int(f['entry_rva'],16),a.pe.rva_read(int(f['entry_rva'],16),f['decoded_bytes'])) for f in functions]
lines=['// Generated by generate_session_close_contract.py; exact current executable.',
       '#pragma once','constexpr SessionBodyContract session_close_bodies[]={']
for rva,body in bodies:
    lines.append('{'+hex(rva)+','+str(len(body))+',{'+','.join(f'0x{x:02x}' for x in hashlib.sha256(body).digest())+'}},')
lines+=['};','']
(root/'native/session_close_contract.hpp').write_text('\n'.join(lines))
report=dict(executable=str(path),executable_sha256=GAME_SHA256,
            close_wrapper={'begin':hex(begin),'end':hex(end),'size':end-begin,
                           'instructions':[{'rva':hex(i.address-a.pe.image_base),'mnemonic':i.mnemonic,'operands':i.op_str} for i in instructions]},
            functions=functions,checks=len(checks),secondary_slot='0x60',secondary_target='0x312b80',
            provenance='tpp-mod 301bf797b7f8032941b21ed56a3570338de6ead4 CloseSession; Dynamite c90f252f8200765f66c005d6bf4357fda0c0d98e TppMain.OnTerminate',
            limitations=['Static inspection only; no close call executed.',
                         'The wrapper can lazily obtain a main session; runtime must prove an existing owned session before authorizing it.',
                         'Mission 50050 uses a different service path; authorization is limited to mission 30050.',
                         'Native close releases/rebuilds member references; returning from the call is not proof of asynchronous cleanup or safe replay.',
                         'Preparing-member disconnect is not newly invoked; full teardown and reconnect remain unverified.'])
(root/'docs/evidence/session-close-contract-2026-09-10.json').write_text(json.dumps(report,indent=2)+'\n')
print('Emitted four complete session-close body contracts, without executing game code.')
