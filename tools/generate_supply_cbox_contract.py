#!/usr/bin/env python3
"""Generate the supply-box observer contract (docs/world-sync-protocol.md section 25) from the exact local PE.

Sites: the two observe-only detours (request_core 0x15C3F00, box_reset 0x15C4080), the request funnel and the
Lua binding's request layout they rely on, and the update's reset bit (the lab remove lever). Static file reads only;
no game code is executed. Run with --check to verify native/supply_cbox_contract.hpp is current.
"""
from pathlib import Path
import argparse, hashlib, json, struct, sys

PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT / 'tools'))
from inspect_game import PEFile

parser = argparse.ArgumentParser()
parser.add_argument('--executable', type=Path, default=Path(r'D:\Games\steamapps\common\MGS_TPP\mgsvtpp.exe'))
parser.add_argument('--sites', type=Path, default=Path(__file__).with_name('supply_cbox_sites.json'))
parser.add_argument('--output', type=Path, default=PROJECT / 'native/supply_cbox_contract.hpp')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

j = json.loads(args.sites.read_text(encoding='utf-8'))
raw = args.executable.read_bytes()
if hashlib.sha256(raw).hexdigest() != j['executable_sha256']:
    raise SystemExit('exact executable hash mismatch')
pe = PEFile(raw)
if pe.image_base != 0x140000000:
    raise SystemExit('unexpected image base')
names = []
lines = ['// Generated by tools/generate_supply_cbox_contract.py from tools/supply_cbox_sites.json (exact retail PE',
         '// SHA-256 ' + j['executable_sha256'] + '). Observe-only detours plus the lab remove lever; see the sites json.',
         '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace mgscoop::supply_cbox_contract {',
         'struct Site {std::uintptr_t rva;std::size_t size;const unsigned char* bytes;};',
         'struct Slot {std::uintptr_t vtable_rva,offset,target_rva;};']
for n, s in enumerate(j['sites']):
    expected = bytes.fromhex(s['bytes'])
    if not expected or len(expected) != s['size'] or len(expected) > 8192:
        raise SystemExit('invalid site size ' + s['name'])
    if hashlib.sha256(expected).hexdigest() != s['sha256']:
        raise SystemExit('evidence bytes sha mismatch ' + s['name'])
    if pe.rva_read(s['rva'], len(expected)) != expected:
        raise SystemExit('code bytes mismatch ' + s['name'])
    names.append(s['name'])
    lines.append('inline constexpr unsigned char %s_bytes[]={%s};' % (s['name'], ','.join('0x%02x' % v for v in expected)))
lines.append('inline constexpr Site sites[]={' + ','.join('{0x%x,sizeof(%s_bytes),%s_bytes}' % (s['rva'], s['name'], s['name'])
                                                          for s in j['sites']) + '};')
for s in j['slots']:
    if struct.unpack('<Q', pe.rva_read(s['vtable_rva'] + s['offset'], 8))[0] != pe.image_base + s['target_rva']:
        raise SystemExit('slot mismatch')
lines.append('inline constexpr Slot slots[]={' + ','.join('{0x%x,0x%x,0x%x}' % (s['vtable_rva'], s['offset'], s['target_rva'])
                                                          for s in j['slots']) + '};')
rva = {s['name']: s['rva'] for s in j['sites']}
for key in ('request_core', 'box_reset'):
    if key not in rva:
        raise SystemExit('missing site ' + key)
lines += ['inline constexpr std::uintptr_t request_core_rva=0x%x;' % rva['request_core'],
          'inline constexpr std::uintptr_t box_reset_rva=0x%x;' % rva['box_reset'],
          '// The box core Z (request_core / box_reset rcx): state, flags, the stored request.',
          'inline constexpr std::size_t box_state=0xf0,box_flags=0x124,box_request=0x4e0;',
          '// The flags bit the update tests (update_reset_bit) to reset the box (reset_path).',
          'inline constexpr std::uint32_t reset_bit=2;',
          '// The 0x130-byte request (lua_request_tail).',
          'inline constexpr std::size_t request_size=0x130,request_drop=0x0,request_equip=0x4,request_parts=0x8,request_pos=0x100,',
          '                             request_aim_object=0x110,request_wait=0x112,request_level=0x120,request_flags=0x12d;',
          '} // namespace mgscoop::supply_cbox_contract']
result = '\n'.join(lines) + '\n'
if args.check:
    if not args.output.exists() or args.output.read_text(encoding='utf-8') != result:
        raise SystemExit('Generated contract is stale')
else:
    args.output.write_text(result, encoding='utf-8')
print('supply cbox contract:', len(j['sites']), 'sites,', len(j['slots']), 'slots')
