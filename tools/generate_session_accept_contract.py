"""Verify MGSV's existing Lua admission call and emit its live byte checks."""
import hashlib
import json
import struct
from pathlib import Path
from analyze_network_bindings import Analysis
from analyze_host_allocations import GAME_SHA256

root = Path(__file__).resolve().parent.parent
raw = Path('D:/Games/steamapps/common/MGS_TPP/mgsvtpp.exe').read_bytes()
assert hashlib.sha256(raw).hexdigest() == GAME_SHA256
analysis = Analysis(raw)
functions = [analysis.function(rva) for rva in (0xA1B5B0, 0x313780, 0x3134A0)]
rows = {int(row['rva'], 16): (row['mnemonic'], row['operands'])
        for function in functions for row in function['instructions']}
checks = {
    0xA1B5BE: ('call', '0x141a12300'),
    0xA1B5C3: ('cmp', 'eax, 1'),
    0xA1B5CD: ('call', '0x141a120c0'),
    0xA1B5D4: ('call', '0x140313780'),
    0xA1B5DE: ('setne', 'dl'),
    0xA1B5E4: ('call', 'qword ptr [r8 + 0x70]'),
    0x31378D: ('mov', 'rax, qword ptr [rip + 0x288a81c]'),
    0x313797: ('jne', '0x140313807'),
    0x3134A0: ('test', 'dl, dl'),
    0x3134A2: ('setne', 'al'),
    0x3134A5: ('mov', 'byte ptr [rcx + 0xe2], al'),
    0x3134AB: ('ret', ''),
}
for rva, expected in checks.items():
    assert rows.get(rva) == expected, hex(rva)
assert 0x313794 + 0x288A81C == 0x2B9DFB0
assert struct.unpack('<Q', analysis.pe.rva_read(0x2126F70 + 0x70, 8))[0] == analysis.pe.image_base + 0x3134A0
assert all(f['complete_declared_range_decoded'] for f in functions)
report = {'executable_sha256': GAME_SHA256, 'semantic_checks': len(checks),
          'session_table_rva': '0x2126f70', 'accept_slot_offset': '0x70',
          'existing_session_root_rva': '0x2b9dfb0', 'functions': functions,
          'limitations': ['File inspection only. No engine calls or writes. Runtime must require the existing owned host before invoking the Lua interface.']}
(root / 'docs/evidence/session-accept-contract-2026-09-09.json').write_text(json.dumps(report, indent=2) + '\n')
lines = ['// Generated by tools/generate_session_accept_contract.py; exact game build.',
         '#pragma once', 'constexpr SessionBodyContract session_accept_bodies[] = {']
for f in functions:
    digest = bytes.fromhex(f['decoded_bytes_sha256'])
    lines.append('    {' + f["entry_rva"] + ',' + str(f['decoded_bytes']) + ',{' + ','.join(f'0x{b:02x}' for b in digest) + '}},')
lines.append('};')
(root / 'native/session_accept_contract.hpp').write_text('\n'.join(lines) + '\n')
print(f'{len(checks)} instruction checks, session table slot and existing-root branch verified; 3 body contracts emitted')
