"""Map named local/host trap predicates from the fingerprinted PE; no execution."""
import hashlib
import json
import struct
from pathlib import Path
from analyze_network_bindings import Analysis
from analyze_host_allocations import GAME_SHA256

root=Path(__file__).resolve().parent.parent
path=Path('D:/Games/steamapps/common/MGS_TPP/mgsvtpp.exe')
raw=path.read_bytes()
assert hashlib.sha256(raw).hexdigest()==GAME_SHA256
a=Analysis(raw)
entries=[0x587E70,0x588850]
functions=[a.function(r) for r in entries]
support=[a.function(r) for r in [0x587D80,0x588760,0x5880B0,0x588A80,0x1BA0600,0x1E02B50,0x53C990]]
rows={int(i['rva'],16):(i['mnemonic'],i['operands']) for f in functions+support for i in f['instructions']}
checks={
    0x587E76:('mov','rbx, rdx'), 0x587E79:('test','rdx, rdx'),
    0x587E86:('call','0x141ba0600'), 0x587E95:('cmp','ax, cx'),
    0x587E9A:('mov','ecx, 0xfe00'),0x587E9F:('test','cx, ax'),
    0x587EA9:('call','0x141e02b50'),0x587EB9:('and','ecx, 0x1ff'),
    0x587EBF:('cmp','dword ptr [rsp + 0x40], ecx'),0x587EC3:('sete','al'),
    0x587EE7:('mov','al, 1'),0x587EEF:('xor','al, al'),
    0x588856:('mov','rbx, rdx'),0x588859:('test','rdx, rdx'),
    0x588866:('call','0x141ba0600'),0x588875:('cmp','ax, cx'),
    0x58887A:('mov','ecx, 0xfe00'),0x58887F:('test','cx, ax'),
    0x588884:('call','0x140bff050'),0x588889:('mov','rcx, qword ptr [rax + 0x78]'),
    0x588890:('call','qword ptr [rax + 0x40]'),0x588893:('test','rax, rax'),
    0x58889B:('mov','rcx, rax'),0x58889E:('call','qword ptr [rdx + 0x28]'),
    0x5888BE:('mov','al, 1'),0x5888C6:('xor','al, al'),
    0x1BA0600:('movzx','eax, word ptr [rcx + 0x68]'),
    0x1BA0604:('mov','word ptr [rdx], ax'),
    0x1E02B50:('jmp','0x14053c990'),0x53C996:('cmp','eax, 0x10'),
    0x53C999:('mov','dword ptr [rcx], eax'),0x53C99B:('setb','al'),
    0x587DCC:('lea','rax, [rip + 0x1c18215]'),0x587DD3:('mov','qword ptr [rbx], rax'),
    0x5887AC:('lea','rax, [rip + 0x1c17cc5]'),0x5887B3:('mov','qword ptr [rbx], rax'),
    0x588104:('lea','rdx, [rip + 0x1c17f2d]'),
    0x588AD4:('lea','rdx, [rip + 0x1c179e5]'),
}
assert all(rows.get(r)==expected for r,expected in checks.items())
assert all(f['complete_declared_range_decoded'] for f in functions)
names={0x21A0038:'TppTrapCheckIsPlayerAndLocalCallbackDataElement',0x21A04C0:'TppTrapCheckIsPlayerAndHostCallbackDataElement'}
assert all(a.pe.cstring(r)==s for r,s in names.items())
slots={0x219FFF8:0x587E70,0x21A0488:0x588850,0x21A0010:0x587D80,0x21A04A0:0x588760}
assert all(struct.unpack('<Q',a.pe.rva_read(r,8))[0]==a.pe.image_base+t for r,t in slots.items())
lines=['// Generated by generate_trap_contract.py for the fingerprinted executable.',
       '#pragma once','#include <cstddef>','#include <cstdint>','namespace mgscoop::trap_contract {']
for name,f in zip(['local','host'],functions):
    body=a.pe.rva_read(int(f['entry_rva'],16),f['decoded_bytes'])
    lines += [f'inline constexpr std::uintptr_t {name}_rva={f["entry_rva"]};',
              f'inline constexpr unsigned char {name}_body[]={{'+','.join(f'0x{x:02x}' for x in body)+'};']
lines+=['struct Slot {std::uintptr_t rva,target;};','inline constexpr Slot slots[]={'+','.join('{'+hex(r)+','+hex(t)+'}' for r,t in slots.items())+'};','}','']
(root/'native/trap_contract.hpp').write_text('\n'.join(lines))
report=dict(executable=str(path),executable_sha256=GAME_SHA256,functions=functions,supporting_functions=support,
    instruction_checks=len(checks),names={hex(r):s for r,s in names.items()},slots={hex(r):hex(t) for r,t in slots.items()},
    provenance='Dynamite c90f252f8200765f66c005d6bf4357fda0c0d98e three TrapCheckIsPlayerAndLocal/Host return-value patches, GPLv3 with Commons Clause 1.0',
    mapping='Named data-element registration and construction lead to local/host tables; callback slot +0x10 takes object in RDX, reads its ID at +0x68, and returns Boolean in AL. Local compares the low nine ID bits with the published local index. Host calls native session IsHost. Both have non-player type fallback and null/false returns.',
    replacement='Call the original callback with both arguments, then return true during active adapter-owned co-op; forward its result otherwise. This preserves the effect of all three upstream return changes, including false/null and non-player paths.',
    limitations=['Static file mapping only; no trap callback or game code was executed.',
                 'The upstream local SETZ byte sequence contains an apparent ModRM typo; current code is mapped by named types, constructor tables and complete dataflow rather than blindly accepting that old byte pattern.',
                 'True predicates broaden trigger eligibility beyond player objects. This is upstream behavior, not evidence that every mission trigger is appropriate for co-op.',
                 'Crash prevention, event ordering, duplicate trigger effects and session teardown are unverified.'])
(root/'docs/evidence/trap-contract-2026-09-10.json').write_text(json.dumps(report,indent=2)+'\n')
print('Emitted two complete named trap callback contracts and registration/dataflow evidence.')
