"""Generate the native exact-build body gate from the recorded job analysis.

Requires the original executable fingerprint; emits hashes and one detour
prologue, not a distributable game binary. No game process is accessed.
"""
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
report=json.loads((ROOT/'docs/evidence/job-lifetime-analysis-2026-09-09.json').read_text())
data=Path('D:/Games/steamapps/common/MGS_TPP/mgsvtpp.exe').read_bytes()
if hashlib.sha256(data).hexdigest()!=report['executable_sha256'].lower():
    raise SystemExit('Executable fingerprint differs')
bodies=report['bodies']
lines=['// Generated by tools/generate_session_allocation_contract.py.',
       '// Source: docs/evidence/job-lifetime-analysis-2026-09-09.json.',
       '#pragma once',
       'struct SessionBodyContract { std::uintptr_t rva; std::size_t size; unsigned char sha256[32]; };',
       'constexpr SessionBodyContract session_bodies[]={']
for name,body in bodies.items():
    digest=bytes.fromhex(body['decoded_bytes_sha256'])
    begin=int(body['entry_rva'],16)
    size=body['decoded_bytes']
    lines.append('    {0x%x,%d,{%s}}, // %s' % (begin,size,','.join('0x%02x'%x for x in digest),name))
lines+=['};']
block=bodies['block_heap_alloc']
prologue=b''.join(bytes.fromhex(row['bytes_hex']) for row in block['instructions'])
if len(prologue)>96 or len(prologue)!=block['decoded_bytes']:
    raise SystemExit('Invalid detour body length')
lines+=['constexpr unsigned char block_allocator_bytes[]={'+','.join('0x%02x'%x for x in prologue)+'};','']
output=ROOT/'native/session_allocation_contract.hpp'
output.write_text('\n'.join(lines))
print(json.dumps({'bodies':len(bodies),'detour_bytes':len(prologue),'output':str(output)}))
