for rva,target in [(0x9D76AE,0x2298CA8),(0x9D76BC,0x9DAD00)]:
    i=a.instructions(rva,7)[0]
    assert i.mnemonic=='lea' and i.address+i.size+i.operands[1].mem.disp-a.pe.image_base==target
side=[a.function(rva) for rva in [0x313FE0,0x11F64B0,0x9DAD00]]
assert all(f['complete_declared_range_decoded'] for f in side)
helper={int(i['rva'],16):(i['mnemonic'],i['operands']) for i in side[1]['instructions']}
assert helper[0x11F64D6]==('movss','dword ptr [rcx], xmm3')
assert helper[0x11F64EA]==('mov','byte ptr [rcx + 8], 0')
