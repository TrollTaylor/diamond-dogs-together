// Diamond Dogs Together launcher core: the pure text of the co-op session
// (ports of tools/CoopPlay.psm1 and tools/friend/FriendCommon.psm1 of 0.13.x, Steam
// transport only): lab.ini / coop.ini, the link secret, the status line and
// its sentences, the launch evidence, and log redaction. No I/O.
#pragma once
#include <cstdint>
#include <string>
#include <vector>

#include "core_json.hpp"

namespace ddt::core {

// ---- Constants ---------------------------------------------------------------
inline constexpr char kAlphabet[] = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";   // Crockford base32
inline constexpr char kMasterUrl[] = "http://127.0.0.1:47899/tppstm/gate";
inline constexpr char kMarkerText[] = "offline-v1\n";
// The first line of every lab.ini / coop.ini this program writes.
inline constexpr char kHeader[] = "# Generated by Diamond Dogs Together";
// The header of the PowerShell Play-Coop (0.12-0.13), recognised as ours too.
inline constexpr char kOldPlayHeader[] = "# Generated by mgs-coop Play-Coop.ps1 (two-PC play); removed when the game exits.";
inline constexpr char kSteamUrl[] = "steam://rungameid/287700";
inline constexpr std::uint64_t kSteamIdBase = 76561197960265728ull;

// ---- Secrets, Steam IDs -------------------------------------------------------
bool IsCanonicalSecret(const std::string& secret);   // 20 characters of kAlphabet
std::string NewSecret();                              // 100 bits: alphabet[random & 31] x 20
bool IsIndividualSteamId64(const std::string& text);  // 17 digits, no leading zero, individual account
std::string SteamId64FromAccount(std::uint32_t account);   // "" for 0
// link-secret.txt validation (spec 3.2): ok, missing, bad_length, bad_char.
std::string SecretFileStatus(const std::string* bytes);

// ---- lab.ini / coop.ini -------------------------------------------------------
struct LabIniParams {
    std::string role;            // host | guest
    std::string save_dir;        // absolute
    std::string steam_self;      // this PC's SteamID64
    std::string steam_peer;      // guest: the host's SteamID64
    bool steam_wait = false;     // guest: wait for an invite
    std::string steam_dispatch;  // "" | both | fnptr | callback | poll
    std::string partner = "native";   // native | clips
    std::string save_handoff;    // "" | off | stage | scene | always
    std::string travel_lock;     // "" | on | off
    int world = 3;               // 0..3
};
// New-CoopPlayLabIniText -Transport steam with the new header. False + a
// reason for invalid parameters.
bool MakeLabIniText(const LabIniParams& p, std::string& text, std::string& error);
// The settings a session's lab.ini was written from (play-session.json "lab").
json::Value LabRecord(const LabIniParams& p);
bool LabParamsFromRecord(const json::Value& lab, LabIniParams& p, std::string& error);

// character: story | ocelot | dd_male | dd_female | avatar | snake (and the
// older default | quiet); fallback dd_male | dd_female | snake | avatar;
// hud "" | compact | full | off.
bool MakeCoopIniText(const std::string& character, const std::string& fallback, const std::string& hud, std::string& text,
                     std::string& error);
bool IsGeneratedIniText(const std::string& text);   // starts with kHeader or kOldPlayHeader
// key=value lines, '#'/';' comments, trimmed; later keys win.
std::vector<std::pair<std::string, std::string>> ParseIni(const std::string& text);

// The partner keys every play lab.ini carries (Get-PlayPartnerDefaults).
const std::vector<std::pair<const char*, const char*>>& PartnerDefaults();

// ---- Status text -------------------------------------------------------------
enum class Wording { powershell, launcher };
// The link-status "reason" sentence. powershell: tests/fixtures/link-reasons.json
// exactly (the loader's coop_text::FormatLinkReason); launcher: the same, except
// sentences that named the PowerShell tools now name Diamond Dogs Together.
std::string LinkReasonText(const std::string& reason, const std::string& remote_build, const std::string& own_build,
                           bool verified, Wording wording);
std::string SteamEndText(std::int64_t end, Wording wording);
std::string PartnerReasonText(const std::string& reason);
std::string MissionName(std::uint64_t mission);
struct HandoffText {
    std::string segment;   // " | ..." for the status line
    std::string line;      // the sentence said once per change
};
HandoffText GetHandoffText(const std::string& token, int pct, bool guest, Wording wording);
bool HandoffBusyToken(const std::string& token);   // the guest waits for / gets the host's save

// link-status.json -> object, or null when it is not v1 or (expected_pid != 0)
// another process wrote it.
json::Value ParseStatusText(const std::string& text, std::uint32_t expected_pid);
// Format-CoopStatusLine (the PowerShell wording, tested against its vectors).
std::string FormatStatusLine(const json::Value& status, bool host, std::int64_t now_ms, const std::string& own_build);

// ---- Launch evidence (Get-CoopLaunchEvidence, Steam transport) -------------------
struct Evidence {
    std::string state;      // ok | pending | unsafe | old_loader | incomplete
    std::string saves;      // ok | missing | unchanged | wrong_dir (the saves= line)
    std::string master;     // ok | missing | bad (the master_server= line)
    std::vector<std::string> missing, problems;
    std::string link_reason;
};
Evidence GetLaunchEvidence(const std::string& early_log, const std::string& steam_log, const std::string& observer_log,
                           const std::string& save_dir, bool final_check, bool steam);

// ---- Redaction (Hide-FriendSensitiveText + Hide-CoopNetworkText) --------------------
std::string MaskAddress(const std::string& address);   // Get-CoopMaskedAddress
std::string RedactSensitive(const std::string& text);   // SteamIDs, userdata accounts, user names
std::string RedactNetwork(const std::string& text);     // join codes, invite strings, public peer addresses
std::string Redact(const std::string& text);            // both
// For launcher.log: Redact plus every drive path replaced by "<path>".
std::string RedactForLog(const std::string& text);

}  // namespace ddt::core
