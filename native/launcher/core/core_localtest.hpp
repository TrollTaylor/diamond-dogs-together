// Diamond Dogs Together launcher core: the developer's local two-window test
// (Settings > Debug mode, Play > Local test). A native port of
// tools/dev/Play-LocalCoop.ps1 with LocalCoopSession.psm1, LocalCoopWindows.psm1
// and the parts of FriendCommon.psm1 / CoopPlay.psm1 they use:
//
//  - two MGSV copies on this PC: this game folder hosts (Snake), a second game
//    folder joins (Quiet), linked over loopback (lab.ini mode=lab, loopback=1);
//  - the mod is installed in the second copy from this package (the loader and
//    the checked runtime file; an unrelated loader is never replaced);
//  - only separate local-test save copies are used (mgs-coop\local-test-saves,
//    seeded from this folder's co-op copy, never from Steam's userdata), with
//    their TPP_GRAPHICS_CONFIG set to a window of the computed layout;
//  - every activation file is journaled (hash and original bytes) BEFORE it is
//    written, in host mgs-coop\local-test-runs\<id>\session.json, with an
//    ownership pointer in both folders: the same files and format as the
//    PowerShell module, so either tool recovers the other's runs;
//  - after BOTH games exit the files are restored from the journal (hash-
//    checked; a file changed afterwards is kept), also when the launcher was
//    closed: the hidden helper DiamondDogsTogether.exe --local-watch <id>.
// Keyboard/mouse go to the clicked game and controller 0 to the guest through
// lab.ini (xinput=0 / none); nothing here sends input to a game.
