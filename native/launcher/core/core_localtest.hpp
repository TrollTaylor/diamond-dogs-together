// ---- The Win32 seams of a run (tests pass a fake) --------------------------------------------
struct LocalWindow {
    std::uint64_t handle = 0;
    LocalRect rect;
    bool moving = false;   // the user drags or sizes it right now
};
class LocalHost {
public:
    virtual ~LocalHost() = default;
    // Starts `exe` in `dir` (the shell's normal GUI launch). pid/start of the new process.
    virtual bool StartGame(const std::wstring& exe, const std::wstring& dir, std::uint32_t& pid, std::int64_t& start_ms,
                           std::string& error) = 0;
    // The full image path of a running process ("" when it cannot be read).
    virtual std::wstring ProcessImage(std::uint32_t pid) = 0;
    // Starts "<this exe> --local-watch <run_id>" hidden and detached in `game_dir`.
    virtual bool StartHelper(const std::wstring& game_dir, const std::string& run_id, std::uint32_t& pid, std::int64_t& start_ms) = 0;
    // The working area of the monitor this window (or the foreground one) is on, physical pixels.
    virtual bool WorkArea(LocalRect& area, int& dpi) = 0;
    // The visible top-level windows of a process (biggest first).
    virtual std::vector<LocalWindow> Windows(std::uint32_t pid) = 0;
    // SetWindowPos without activation or z-order change.
    virtual bool PlaceWindow(std::uint64_t handle, const LocalRect& rect) = 0;
    // Asks a game to close (its window), and ends it after `wait_ms` if it is still there.
    virtual void CloseGame(std::uint32_t pid, unsigned wait_ms) = 0;
    // Nothing listens on the loopback port (tcp or udp).
    virtual bool PortFree(int port, bool tcp) = 0;
};
std::shared_ptr<LocalHost> MakeWin32LocalHost();

// ---- A run ---------------------------------------------------------------------------------------
struct LocalTestRequest {
    std::wstring host_root, guest_root;
    std::string hud;          // "" | compact | full | off
    int world = 3;
    std::string partner = "native";
    // The fixture mode of the PowerShell test (MGS_COOP_TEST_NO_LAUNCH): no Steam,
    // no port checks, a fixed 1920x1080 area; activation only (no helper, no games).
    bool fixture = false;
};
struct LocalStatus {
    bool active = false;      // the run owns both games (until they exit and the files are restored)
    bool failed = false;      // stopped by a safety check
    std::string headline, detail;
    std::string host_line, guest_line;   // the status line of each game
    std::string host_link;   // the host's link-status.json text (the In game page reads it)
};

// One local test, from the checks to the cleanup. Start() prepares both
// folders and starts both games; Poll() (every 500 ms) watches them, places
// their windows and restores both folders after both exit.
class LocalTestRun {
public:
    LocalTestRun(std::shared_ptr<Env> env, std::shared_ptr<LocalHost> host);
    ~LocalTestRun();
    LocalTestRun(const LocalTestRun&) = delete;
    LocalTestRun& operator=(const LocalTestRun&) = delete;

    // Checks, installs into the second folder, recovers older runs, makes the
    // save copies, journals and writes the files, starts the helper and both
    // games. On failure nothing stays switched on and `error` says why.
    bool Start(const LocalTestRequest& request, std::string& error);
    // false once the run is over (both games gone and the files restored, or never started).
    bool Poll();
    void Arrange();   // place both windows again (the PowerShell test's [R])
    LocalStatus Status() const { return status_; }
    std::string run_id() const { return run_id_; }
    std::wstring run_dir() const { return run_dir_; }
    // The save copies and the layout chosen by Start().
    std::wstring save_dir(bool host) const { return host ? save_dirs_[0] : save_dirs_[1]; }
    LocalLayout layout() const { return layout_; }

private:
    struct Instance {
        std::uint32_t pid = 0;
        std::int64_t start_ms = 0;
        std::wstring exe;
        bool safe = false;
        std::int64_t started_ms = 0;
        std::int64_t offsets[3] = {0, 0, 0};
        std::string texts[3];
        PlacementEntry placement;
        bool has_placement = false;
    };
    bool Fail(const std::string& sentence, std::string& error);
    bool OwnedAlive(const Instance& game, const std::wstring& root);
    void StopOwnedGames();
    void PlaceWindows(bool retile);
    void Finish();   // both games gone: restore both folders from the journal

    std::shared_ptr<Env> env_;
    std::shared_ptr<LocalHost> host_;
    LocalTestRequest request_;
    InstancePaths paths_[2];   // host, guest
    std::wstring save_dirs_[2];
    std::wstring run_dir_;
    std::string run_id_;
    LocalLayout layout_;
    LocalRect area_;
    int dpi_ = 96;
    Instance games_[2];
    bool running_ = false;
    std::int64_t next_poll_ms_ = 0;
    std::string notice_;        // a window that did not take its place
    std::string stop_reason_;   // why a safety check stopped the games
    LocalStatus status_;
};

// DiamondDogsTogether.exe --local-watch <run_id>: the hidden helper in the host
// folder. Restores both folders once both games have exited and the launcher
// window is gone; exits when the journal is off. Returns the exit code.
int RunLocalWatch(Env& env, const std::wstring& host_root, const std::string& run_id);

