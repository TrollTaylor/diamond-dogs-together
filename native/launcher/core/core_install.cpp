bool InstallIsCurrent(const json::Value& state) {
    // A record the PowerShell installer wrote (0.13.x, no "launcher" field) is
    // adopted by running the setup once, whatever its version.
    return state.Str("status") == "installed" && state.Str("version") == CoreVersion() && state.Str("launcher") == "Diamond Dogs Together";
}

