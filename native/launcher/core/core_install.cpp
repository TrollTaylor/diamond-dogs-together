    const std::string stamp = StampNow(env);
    const std::string folder = "mgs-coop-logs-" + role + "-" + stamp;
    ZipWriter zip;
    std::uint16_t dos_time = 0, dos_date = 0;
    {
        const Civil c = env.LocalTime(env.NowMs());
        ToDosDateTime(c.year, c.month, c.day, c.hour, c.minute, c.second, dos_time, dos_date);
    }
    zip.SetTimestamp(dos_time, dos_date);
    std::vector<std::string> included, missing;
    std::size_t entries = 0;
