// ---- Uninstall --------------------------------------------------------------------------
bool Uninstall(Env& env, const InstancePaths& paths, std::string& report, std::string& error) {
    report.clear();
    if (AnyGameRunningIn(env, paths.game)) {
        error = "MGSV is running from this folder. Quit the game normally, then try again. Nothing was changed.";
        return false;
    }
    if (PlaySessionLive(env, paths)) {
        error = "Co-op is still on for a game started from this folder. Quit MGSV, then try again. Nothing was changed.";
        return false;
    }
    std::vector<std::string> lines;
    const std::string stamp = StampNow(env);
    LauncherLog(env, paths, "uninstall=start");
    json::Value state;
    const bool have_state = ReadInstallState(paths, state);
    if (IsDir(paths.mod)) {
        const CleanupResult c = CleanupSession(env, paths, false);
        if (c.ran && !c.removed.empty()) lines.push_back("Switched off the last co-op session.");
        for (const std::string& m : c.messages) lines.push_back(m);
        RemoveStaleHandoff(env, paths);
    }
    // The loader: only this package's.
    const PackageInfo package = ReadPackage(paths);
    bool loader_left = IsFile(paths.loader);
    if (loader_left) {
        if (LoaderIsOurs(paths, package)) {
            if (DeleteFileChecked(paths.loader)) {
                loader_left = false;
                lines.push_back("The mod's loader (dinput8.dll) was removed from your game folder.");
            } else {
                lines.push_back("The mod's loader (dinput8.dll) could not be removed (is MGSV running?). Delete it yourself from the game folder.");
            }
        } else {
            lines.push_back("A dinput8.dll that is not this package's is in your game folder (another mod, or another version). It was "
                            "left alone.");
        }
    } else {
        lines.push_back("No mod loader (dinput8.dll) is in your game folder.");
    }
    // The co-op configuration: set aside, never deleted.
    if (IsDir(paths.mod)) {
        int renamed = 0;
        for (const char* name : {"lab.ini", "coop.ini", "link-secret.txt", "script-observe.enabled"})
            if (!RenameAside(JoinPath2(paths.mod, Wide(name)), "disabled", stamp).empty()) ++renamed;
        if (renamed) lines.push_back("Co-op settings files were set aside (renamed *.disabled-" + stamp + ").");
        if (loader_left && have_state) {
            // A loader remains: its configuration from before the first install comes back with it.
            for (const json::Value* row : Rows(state.Find("previous_files"))) {
                const std::string name = row->Str("name"), copy = row->Str("copy");
                if (!row->Bool("existed") || copy.empty() || !IsFile(Wide(copy))) continue;
                if (name != "lab.ini" && name != "coop.ini" && name != "script-observe.enabled" && name != "client-host.txt") continue;
                std::string copy_error;
                if (CopyFileChecked(Wide(copy), JoinPath2(paths.mod, Wide(name)), true, copy_error))
                    lines.push_back(name + " from before the first install was put back for the remaining loader.");
            }
        }
        if (have_state) RenameAside(paths.friend_install, "uninstalled", stamp);
    }
    // The real saves against the first backup (information only).
    Baselines base;
    if (have_state) {
        base = SaveBaselines(StringList(state.Find("backups")));
        if (base.backups.empty() && !state.Str("latest_backup").empty()) base = SaveBaselines({Wide(state.Str("latest_backup"))});
    }
    if (base.backups.empty()) {
        lines.push_back("No backup of your real saves was found, so they could not be compared.");
    }
    for (const std::wstring& b : base.backups) {
        const RealSaveCheck check = CheckRealSavesAgainstBackup(b);
        if (!check.ok) continue;
        if (check.comparison.same) {
            lines.push_back("Your real saves match the backup made when co-op was set up (checked by SHA-256).");
            continue;
        }
        lines.push_back("Your real saves differ from the backup made when co-op was set up (" + std::to_string(check.comparison.changed.size()) +
                        " changed, " + std::to_string(check.comparison.missing.size()) + " missing, " +
                        std::to_string(check.comparison.added.size()) + " new). That is expected if you played without co-op in between; "
                        "nothing was overwritten.");
        lines.push_back("To go back to that backup: quit Steam, then copy the contents of mgs-coop\\real-save-backups\\" + Utf8(LeafOf(b)) +
                        "\\files\\287700\\local and \\files\\311340\\remote over the same folders in Steam\\userdata\\<your account>.");
    }
    if (have_state && state.Find("firewall_rule") && !state.Find("firewall_rule")->is_null())
        lines.push_back("A Windows Firewall rule 'mgs-coop play' from an earlier version stays; remove it in Windows Defender Firewall if "
                        "you no longer need it.");
    lines.push_back("Kept: your co-op save and the save backups in the mgs-coop folder.");
    lines.push_back("To remove everything, delete DiamondDogsTogether.exe and the mgs-coop folder yourself.");
    for (std::size_t i = 0; i < lines.size(); ++i) report += (i ? "\n" : "") + lines[i];
    LauncherLog(env, paths, std::string("uninstall=done; loader_left=") + (loader_left ? "1" : "0"));
    return true;
}

