constexpr char kFriendHeader[] = "# Generated by the MGS Co-op friend-test installer (Install-Coop.ps1)";
const char* const kManaged[] = {"lab.ini", "coop.ini", "script-observe.enabled", "client-host.txt", "link-secret.txt"};

bool ReadJson(const std::wstring& path, json::Value& out, std::uint64_t max = 4u << 20) {
    std::string text;
    if (!IsFile(path) || !ReadTextShared(path, text, max)) return false;
    return json::Parse(text, out);
}

std::vector<const json::Value*> Rows(const json::Value* v) {
    std::vector<const json::Value*> out;
    if (!v) return out;
    if (v->is_object()) out.push_back(v);
    else
        for (const json::Value& e : v->Elements()) out.push_back(&e);
    return out;
}

std::vector<std::wstring> StringList(const json::Value* v) {
    std::vector<std::wstring> out;
    if (!v) return out;
    if (v->is_string()) out.push_back(Wide(v->StringRef()));
    else
        for (const json::Value& e : v->Elements())
            if (e.is_string() && !e.StringRef().empty()) out.push_back(Wide(e.StringRef()));
    return out;
}

json::Value AsArray(const json::Value* v) {
    if (!v || v->is_null()) return json::Value::Array();
    if (v->is_array()) return *v;
    json::Value a = json::Value::Array();
    a.Push(*v);
    return a;
}

std::wstring RenameAside(const std::wstring& path, const std::string& suffix, const std::string& stamp) {
    if (!IsFile(path)) return {};
    const std::wstring base = path + L"." + Wide(suffix) + L"-" + Wide(stamp);
    const std::wstring target = UniquePath(base, L"");
    std::string error;
    return MovePath(path, target, error) ? target : std::wstring();
}

std::string OnlineArchiveReason(const std::string& name, const std::string& text) {
    if (name == "client-host.txt") return "online join target";
    if (name == "link-secret.txt") return {};
    if (name == "script-observe.enabled") {
        const std::string t = Trim(text);
        return t == "host-v3" || t == "client-v1" ? "online role marker" : std::string();
    }
    std::string body = text;
    if (body.size() >= 3 && static_cast<unsigned char>(body[0]) == 0xEF) body = body.substr(3);
    return StartsWith(body, kFriendHeader) ? "online friend-test configuration" : std::string();
}

// Leftovers of a run that was killed: WriteAtomic temps, the archive builder's
// temp file and an unfinished co-op copy seed.
void RemoveStaleTemps(const InstancePaths& paths) {
    for (const DirEntry& e : ListDirectory(paths.mod)) {
        const std::string name = Utf8(e.name);
        if (e.directory) {
            if (StartsWith(name, "coop-saves-seed-") && !e.reparse) RemoveTree(JoinPath2(paths.mod, e.name));
            continue;
        }
        bool ours = StartsWith(name, "mgs-coop-player-runtime.dat.tmp-");
        if (!ours && EndsWith(name, ".tmp") && name.size() > 37) {
            const std::string hex = name.substr(name.size() - 36, 32);
            ours = name[name.size() - 37] == '.' && IsHexText(hex, 32);
        }
        if (ours) DeleteFileChecked(JoinPath2(paths.mod, e.name));
    }
}

// An import killed between its two folder moves leaves no coop-saves but a
// complete coop-saves-new-* copy: put the newest one in place.
void RecoverInterruptedImport(Env& env, const InstancePaths& paths) {
    if (IsDir(paths.coop_saves)) return;
    std::wstring best;
    for (const DirEntry& e : ListDirectory(paths.mod)) {
        if (!e.directory || e.reparse || !StartsWith(Utf8(e.name), "coop-saves-new-")) continue;
        const std::wstring dir = JoinPath2(paths.mod, e.name);
        if (IsFile(JoinPath2(dir, L"imported-progress.json")) && IsDir(JoinPath2(dir, L"287700\\local"))) best = dir;
    }
    std::string error;
    if (!best.empty() && MovePath(best, paths.coop_saves, error)) LauncherLog(env, paths, "recovered=interrupted_import");
}

