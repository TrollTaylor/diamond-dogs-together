// ---- Settings ------------------------------------------------------------------------
bool LoadSettings(const InstancePaths& paths, Settings& out) {
    out = Settings{};
    json::Value v;
    if (!ReadJson(paths.settings, v, 1u << 20) || !v.is_object()) return false;
    out.raw = v;
    const std::string c = v.Str("character");
    out.character = IsJoinerCharacter(c) ? c : std::string();
    const std::string h = v.Str("hud");
    out.hud = (h == "compact" || h == "full" || h == "off") ? h : std::string();
    out.debug = v.Bool("debug", false);
    out.local_guest = v.Str("local_test_guest");
    return true;
}

bool SaveSettings(const InstancePaths& paths, Settings& s, std::string& error) {
    if (!IsDir(paths.mod)) {
        error = "the mgs-coop folder is missing";
        return false;
    }
    if (!s.raw.is_object()) s.raw = json::Value::Object();
    s.raw["format"] = "ddt-launcher-settings";
    s.raw["v"] = 1;
    s.raw["character"] = s.character;
    s.raw["hud"] = s.hud;
    s.raw["debug"] = s.debug;
    s.raw["local_test_guest"] = s.local_guest;
    return WriteAtomic(paths.settings, json::Dump(s.raw) + "\n", true, error);
}

bool CachedFileSha256(const InstancePaths& paths, Settings& settings, const std::wstring& file, std::string& hex) {
    WIN32_FILE_ATTRIBUTE_DATA d{};
    if (!GetFileAttributesExW(file.c_str(), GetFileExInfoStandard, &d) || (d.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)) return false;
    const std::uint64_t size = (static_cast<std::uint64_t>(d.nFileSizeHigh) << 32) | d.nFileSizeLow;
    ULARGE_INTEGER u{};
    u.LowPart = d.ftLastWriteTime.dwLowDateTime;
    u.HighPart = d.ftLastWriteTime.dwHighDateTime;
    const std::int64_t write = static_cast<std::int64_t>(u.QuadPart);
    const std::string key = LowerAscii(Utf8(LeafOf(file)));
    json::Value& cache = settings.raw["file_hashes"];
    if (!cache.is_object()) cache = json::Value::Object();
    if (const json::Value* row = cache.Find(key)) {
        if (row->Int("size", -1) == static_cast<std::int64_t>(size) && row->Int("write", -1) == write && IsHexText(row->Str("sha256"), 64)) {
            hex = row->Str("sha256");
            return true;
        }
    }
    std::uint64_t got = 0;
    if (!Sha256FileHex(file, hex, &got)) return false;
    json::Value row = json::Value::Object();
    row["size"] = static_cast<std::int64_t>(got);
    row["write"] = write;
    row["sha256"] = hex;
    cache[key] = row;
    std::string error;
    if (IsDir(paths.mod) && IsFile(paths.settings)) SaveSettings(paths, settings, error);
    return true;
}

bool IsJoinerCharacter(const std::string& v) {
    return v == "story" || v == "ocelot" || v == "dd_male" || v == "dd_female" || v == "avatar";
}

std::string JoinerCharacter(const std::string& value) {
    if (value == "quiet") return "story";
    return IsJoinerCharacter(value) ? value : std::string("dd_male");
}

// ---- package.json and the hash gates -------------------------------------------------
PackageInfo ReadPackage(const InstancePaths& paths) {
    PackageInfo p;
    const std::string damaged =
        "mgs-coop\\package.json is missing or damaged. Extract the whole Diamond Dogs Together zip into the game folder again.";
    json::Value v;
    if (HasReparsePoint(paths.package_json, paths.game) || !ReadJson(paths.package_json, v, 1u << 20) || !v.is_object() ||
        v.Str("product") != kPackageProduct) {
        p.problem = damaged;
        return p;
    }
    p.version = v.Str("version");
    if (p.version != CoreVersion()) {
        p.problem = "The files in this folder come from different Diamond Dogs Together versions (the package is " + p.version +
                    ", this program is " + CoreVersion() + "). Extract the whole zip into the game folder again.";
        return p;
    }
    int loaders = 0;
    for (const json::Value* row : Rows(v.Find("files"))) {
        if (row->Str("target") != "dinput8.dll") continue;
        ++loaders;
        p.loader_sha256 = UpperAscii(row->Str("sha256"));
    }
    if (loaders != 1 || !IsHexText(p.loader_sha256, 64)) {
        p.problem = damaged;
        return p;
    }
    const std::string exe = v.Str("executable_sha256"), steam = v.Str("steam_dll_sha256");
    std::string archive;
    if (const json::Value* ra = v.Find("runtime_archive"); ra && ra->is_object()) archive = ra->Str("sha256");
    if ((!exe.empty() && UpperAscii(exe) != kExeSha256) || (!steam.empty() && UpperAscii(steam) != kSteamApiSha256) ||
        (!archive.empty() && LowerAscii(archive) != kRuntimeDatSha256)) {
        p.problem = damaged;
        return p;
    }
    p.ok = true;
    return p;
}

std::string GameFileProblem(const InstancePaths& paths, Settings& settings, const PackageInfo& package) {
    std::string hex;
    if (!CachedFileSha256(paths, settings, paths.exe, hex) || hex != UpperAscii(Hooks().exe_sha256))
        return "mgsvtpp.exe is not the expected Steam version (1.0.15.4, unmodified). This mod only supports that exact game version. "
               "Verify the game files in Steam (Properties > Installed Files), then press Check again.";
    if (!IsFile(paths.steam_api) || !Sha256FileHex(paths.steam_api, hex) || hex != UpperAscii(Hooks().steam_api_sha256))
        return "steam_api64.dll is not the original file shipped with the game. Verify the game files in Steam (Properties > Installed "
               "Files), then press Check again.";
    if (!package.ok) return package.problem;
    if (!IsFile(paths.loader))
        return "dinput8.dll is missing from the game folder. Extract the whole Diamond Dogs Together zip into the game folder again.";
    if (HasReparsePoint(paths.loader, paths.game) || !Sha256FileHex(paths.loader, hex) || hex != package.loader_sha256)
        return "dinput8.dll in the game folder is not the one from this Diamond Dogs Together package (another mod, or another "
               "version). Extract the whole zip into the game folder again and replace the file.";
    return {};
}

bool LoaderIsOurs(const InstancePaths& paths, const PackageInfo& package) {
    std::string hex;
    return package.ok && IsFile(paths.loader) && Sha256FileHex(paths.loader, hex) && hex == package.loader_sha256;
}

// ---- Steam account ---------------------------------------------------------------------
std::uint32_t SteamActiveUser(Env& env) {
    std::uint32_t v = 0;
    return env.RegDword(false, L"Software\\Valve\\Steam\\ActiveProcess", L"ActiveUser", v) ? v : 0;
}

std::uint64_t OwnSteamId(Env& env) {
    const std::uint32_t a = SteamActiveUser(env);
    return a ? kSteamIdBase + a : 0;
}

SteamAccount ResolveSteamAccount(Env& env) {
    SteamAccount s;
    std::wstring path;
    if (!env.RegString(false, L"Software\\Valve\\Steam", L"SteamPath", path) || path.empty()) {
        s.problem = "Steam was not found for this Windows user. Install and start Steam, log in, then try again.";
        return s;
    }
    std::replace(path.begin(), path.end(), L'/', L'\\');
    s.steam_root = FullPath(path);
    const std::uint32_t active = SteamActiveUser(env);
    if (active) {
        s.account = active;
        s.active = true;
    } else {
        std::vector<std::uint32_t> candidates;
        for (const DirEntry& e : ListDirectory(JoinPath2(s.steam_root, L"userdata"))) {
            if (!e.directory || e.name.size() > 10 || e.name.empty()) continue;
            bool digits = true;
            for (wchar_t c : e.name)
                if (c < L'0' || c > L'9') digits = false;
            if (!digits) continue;
            const std::uint64_t id = std::stoull(e.name);
            if (id == 0 || id > 0xFFFFFFFFull) continue;
            if (IsDir(JoinPath2(JoinPath2(JoinPath2(s.steam_root, L"userdata"), e.name), L"287700\\local")))
                candidates.push_back(static_cast<std::uint32_t>(id));
        }
        if (candidates.empty()) {
            s.problem = "No Steam account with MGSV saves was found (Steam is not running). Start Steam, log in, play MGSV once "
                        "normally, then try again.";
            return s;
        }
        if (candidates.size() > 1) {
            s.problem = "Several Steam accounts on this PC have MGSV saves and Steam is not running. Start Steam and log in with your "
                        "own account, then try again.";
            return s;
        }
        s.account = candidates.front();
    }
    s.userdata = JoinPath2(JoinPath2(s.steam_root, L"userdata"), std::to_wstring(s.account));
    s.ok = true;
    return s;
}

