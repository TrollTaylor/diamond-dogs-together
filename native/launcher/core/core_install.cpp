bool RuntimeArchiveValid(const InstancePaths& paths, Settings* settings, std::string& error) {
    if (Hooks().verify_runtime) return Hooks().verify_runtime(paths.archive, error);
    if (!settings) return VerifyRuntimeDat(paths.archive, error);
    std::string hex;
    if (FileSizeOrZero(paths.archive) != kRuntimeDatSize || !CachedFileSha256(paths, *settings, paths.archive, hex) ||
        LowerAscii(hex) != kRuntimeDatSha256) {
        error = "the runtime archive is missing or changed";
        return false;
    }
    return true;
}

