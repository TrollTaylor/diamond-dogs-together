namespace ddt::core {

int RunSelfTest(const std::wstring& exe_dir, std::string& report) {
    int checks = 0, failures = 0;
    auto check = [&](bool ok, const std::string& what) {
        ++checks;
        if (!ok) {
            ++failures;
            report += "FAIL: core: " + what + "\n";
        }
    };
    auto info = [&](const std::string& line) { report += "info: " + line + "\n"; };

    std::string error;
    check(CheckEmbeddedRuntimeAssets(error), "embedded runtime assets (" + error + ")");

    // Join codes (vectors shared with tests/friend_package_tests.ps1).
    const std::string code = FormatJoinCode("ABCDE12345FGHJK67890", 76561197960365728ull);
    check(code == "MGS2-ABCDE-12345-FGHJK-67890-4G@76561197960365728", "MGS2 code vector");
    std::string secret;
    std::uint64_t host = 0;
    check(ParseJoinCode(" mgs2 abcde i2345 fghjk 67890 4g @ 76561197960365728", secret, host) && secret == "ABCDE12345FGHJK67890" &&
              host == 76561197960365728ull,
          "MGS2 tolerant parse");
    check(!CheckJoinCode(code, 76561197960365728ull).ok, "own code refused");
    const std::string fresh = NewSecret();
    check(IsCanonicalSecret(fresh), "random link secret");

    // Session file texts.
    ActivationRequest req;
    req.lab.role = "guest";
    req.lab.save_dir = "C:\\Games\\MGS_TPP\\mgs-coop\\coop-saves";
    req.lab.steam_self = "76561197960465728";
    req.lab.steam_peer = "76561197960365728";
    req.lab.save_handoff = "scene";
    req.secret = fresh;
    req.character = "story";
    req.hud = "compact";
    std::vector<std::pair<std::string, std::string>> files;
    const bool texts = SessionFileTexts(req, files, error);
    check(texts && files.size() == 4 && files[0].first == "lab.ini" && files[1].first == "link-secret.txt" && files[2].first == "coop.ini" &&
              files[3].first == "script-observe.enabled" && files[3].second == "offline-v1\n",
          "session file order and marker");
    check(texts && StartsWith(files[0].second, "# Generated by Diamond Dogs Together\nenabled=1\nmode=play\nrole=guest\n") &&
              files[0].second.find("net_peer_steam=76561197960365728\n") != std::string::npos && EndsWith(files[0].second, "save_handoff=scene\nworld=3\n"),
          "lab.ini text");
    check(texts && files[2].second.find("\ncharacter=story\ncharacter_fallback=dd_male\nhud=compact\n") != std::string::npos, "coop.ini text");
    check(PlayMutexName(L"C:\\Games\\MGS_TPP").size() == 36 && PlayMutexName(L"C:\\Games\\MGS_TPP") == PlayMutexName(L"c:\\games\\mgs_tpp\\"),
          "play mutex name");
    const std::string redacted = Redact("code " + code + " id 76561197960365728");
    check(redacted.find("ABCDE") == std::string::npos && redacted.find("76561197960365728") == std::string::npos, "redaction");

    // The model on a throwaway folder (nothing in the game folder is touched).
    auto env = MakeWin32Env();
    const std::wstring temp = JoinPath2(env->TempDir(), L"ddt-selftest-" + Wide(RandomHex(6)));
    if (CreateDirectories(temp)) {
        {
            auto model = MakeRealModelWithEnv(temp, env);
            check(model->phase() == Phase::not_in_game_folder, "model: a folder without mgsvtpp.exe");
        }
        std::string write_error;
        if (WriteAtomic(JoinPath2(temp, L"mgsvtpp.exe"), std::string("not the game"), false, write_error)) {
            auto model = MakeRealModelWithEnv(temp, env);
            check(model->phase() == Phase::error && !model->last_error().empty(), "model: a wrong mgsvtpp.exe is refused");
            std::string code_out, host_error;
            check(!model->host(code_out, host_error) && !host_error.empty() && code_out.empty(), "model: no hosting while refused");
        }
        RemoveTree(temp);
    } else {
        check(false, "temp folder");
    }

    // The environment (read-only, information only).
    const InstancePaths paths = GetInstancePaths(exe_dir);
    if (IsFile(paths.exe)) {
        std::string hex;
        info(std::string("game folder: mgsvtpp.exe ") + (Sha256FileHex(paths.exe, hex) && hex == kExeSha256 ? "is" : "is NOT") +
             " the supported version");
        const PackageInfo package = ReadPackage(paths);
        info(std::string("package.json: ") + (package.ok ? "ok" : "missing or not this version"));
        info(std::string("dinput8.dll: ") + (LoaderIsOurs(paths, package) ? "this package's" : "missing or not this package's"));
        json::Value state;
        info(std::string("install: ") + (ReadInstallState(paths, state) ? state.Str("status", "unknown") + " " + state.Str("version") : "not set up"));
        std::string dat_error;
        info(std::string("runtime archive: ") + (VerifyRuntimeDat(paths.archive, dat_error) ? "ok" : "missing or changed"));
    } else {
        info("not started from a game folder (no mgsvtpp.exe next to the exe)");
    }
    info(std::string("Steam: ") + (OwnSteamId(*env) ? "running and logged in" : "not running or not logged in"));
    report += "core selftest: " + std::to_string(checks - failures) + "/" + std::to_string(checks) + " checks passed\n";
    return failures == 0 ? 0 : 1;
}

}  // namespace ddt::core
